const box=new DashboardChatQueue({id:{name:'u:qa'},storage:{kv:storage}},{AUTH_MODE:'accounts'});
const call=(path,body)=>box.fetch(new Request('https://internal/manual/'+path,{method:body?'POST':'GET',...(body?{body:JSON.stringify(body)}:{})}));
